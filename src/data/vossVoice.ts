/** Developer-only lexical guard for narrator leaks. It intentionally targets
 * implementation vocabulary, not ordinary in-world words such as «правило».
 */
export const vossForbiddenDeveloperTerms = [
  "character engine",
  "runtime",
  "парсер",
  "миграц",
  "реализац",
  "интерфейс",
  "в этой кампании",
  "мы используем",
  "мы изменили",
  "совместимост",
  "редакция правил",
] as const

export function vossCommentHasDeveloperLeak(comment: string) {
  const normalized = comment.toLocaleLowerCase("ru")
  return vossForbiddenDeveloperTerms.some((term) => normalized.includes(term))
}
