export function vossTextHasModernRegister(text: string) {
  return containsForbiddenModernRegister(text)
}

export function vossTextHasAbusiveRegister(text: string) {
  return containsForbidden(text, vossForbiddenAbusiveRegister)
}

export function vossTextViolatesVoice(text: string) {
  return vossCommentHasDeveloperLeak(text) || vossTextHasModernRegister(text) || vossTextHasAbusiveRegister(text)
}
