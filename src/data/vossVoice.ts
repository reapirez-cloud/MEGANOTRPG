function containsForbidden(text: string, terms: readonly string[]) {
  const normalized = text.toLocaleLowerCase("ru")
  return terms.some((term) => normalized.includes(term))
}

export function vossCommentHasDeveloperLeak(comment: string) {
  return containsForbidden(comment, vossForbiddenDeveloperTerms)
}

export function vossExplanationHasBoilerplate(explanation: string) {
  return containsForbidden(explanation, vossForbiddenExplanationBoilerplate)
}

export function vossTextHasModernRegister(text: string) {
  return containsForbidden(text, vossForbiddenModernRegister)
}

export function vossTextViolatesVoice(text: string) {
  return vossCommentHasDeveloperLeak(text) || vossTextHasModernRegister(text)
}
