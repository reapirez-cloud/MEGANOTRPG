export type WarlockInvocationReferenceFeature = {
  level: number
  name: string
  explanation: string
  mechanics: string
  details: string[]
  voss: string
}

function invocation(
  level: number,
  name: string,
  nameEn: string,
  mechanics: string,
  details: string[] = [],
): WarlockInvocationReferenceFeature {
  return {
    level,
    name: `Воззвание: ${name}`,
    explanation: "",
    mechanics,
    details: [`Оригинальное название: ${nameEn}.`, ...details],
    voss: "",
  }
}

