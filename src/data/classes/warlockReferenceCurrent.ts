import { warlockReferenceDraft } from "./warlockReferenceDraft"
import { normalizeVossWorldTone } from "./vossWorldTone"

const level20Explanation = `После войны Даниэль исчез. Не героически — просто однажды его место у костра осталось пустым. Я решил, что хозяин наконец утащил своё имущество туда, откуда оно пришло.

Но годы шли, и имя Даниэля время от времени всплывало там, где людям особенно хотелось бы его не слышать.

Караванщики с северного тракта рассказывали о худом полукровке в сером плаще. Будто тот в одиночку разогнал стаю демонов, потом опустился на колени посреди дороги, замер на несколько десятков ударов сердца — и поднялся снова полный той же мерзкой силы, словно до боя вообще не колдовал.

Наёмники с восточной границы клялись, что видели его у сожжённой крепости. Говорили, он уже не носил ни знаков роты, ни человеческих гербов. Только на шее темнел старый след, похожий на ошейник, а за спиной шевелилась тень, которая иногда наклонялась к нему, будто шептала на ухо.

Потом дошёл слух от храмовников. Один из них якобы спросил Даниэля, почему тот, обладая такой силой, до сих пор служит своему покровителю. Полукровка будто бы рассмеялся и ответил: «Служит? Это вы так называете, когда кто-то держит тебя за горло всю жизнь и ты уже не помнишь, как дышать без его пальцев?»

Не знаю, говорил ли он это на самом деле. Солдатский рассказ по дороге обрастает таким мясом, что родная мать не узнает. Может, Даниэль давно мёртв. Может, ходит где-то до сих пор. Может, от человека в нём осталось одно имя.

Но одному в этих слухах я верю. К двадцатому рангу колдун становится чудовищно силён: может выплеснуть всю дарёную мощь, выдохнуться, припасть к своему невидимому ошейнику — и через короткую мольбу подняться снова полным силы.

И вот тут самое мерзкое. Чем сильнее становится цепной пёс, тем труднее понять, почему он всё ещё носит цепь. Со стороны кажется: да порви ты её. А он, может статься, уже сам не знает, где кончается железо хозяина и начинается его собственная шея.

Такую цепь сталью не перерубишь.`

const level20Comment = `Дурень думает: стану достаточно сильным — и порву поводок. А потом сила приходит, поводок остаётся, и выясняется, что за долгие годы ошейник врос в мясо. Вот такую цепь мечом не рубят.`

export const warlockReferenceCurrent = {
  ...warlockReferenceDraft,
  authorDescription: normalizeVossWorldTone(warlockReferenceDraft.authorDescription),
  authorComment: normalizeVossWorldTone(warlockReferenceDraft.authorComment),
  features: warlockReferenceDraft.features.map((feature) => {
    if (feature.level === 20) {
      return {
        ...feature,
        explanation: level20Explanation,
        voss: level20Comment,
      }
    }

    const explanation = normalizeVossWorldTone(feature.explanation)
    let voss = normalizeVossWorldTone(feature.voss)

    if (feature.level === 1) {
      voss = voss.replace("Академический маг", "Учёный маг")
    }
    if (feature.level === 2) {
      voss = `Смотреть на это тошно до спазмов в кишках: парень ползает на брюхе перед пустотой, унижается, а спустя шесть десятков ударов сердца встаёт так, будто хозяин заново налил ему в жилы всю дрянь до краёв. Гордости там нет ни на грош, зато результат на бруствере виден сразу.`
    }
    if (feature.level === 3) {
      return {
        ...feature,
        explanation: explanation.replace("не военный контракт, который можно разорвать у полкового писаря", "не наёмная грамота, которую можно порвать у полкового писаря"),
        voss,
      }
    }
    if (feature.level === 11) {
      voss = `Придворные маги трясут печатями своих академий и учат подобные чары полжизни, дрожа над каждым слогом. Даниэль вбивает себе ржавый гвоздь в мясо — и стирает укреплённый форт с лица земли за один удар сердца. Страшная сила, за которую расплачиваются собственной плотью.`
    }

    return { ...feature, explanation, voss }
  }),
}
