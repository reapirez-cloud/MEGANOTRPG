function normalize(value: string) {
  return value
    .trim()
    .toLowerCase()
    .replace(/ё/g, "е")
    .replace(/[‐‑–—]/g, "-")
    .replace(/\s+/g, " ")
}

function isSamurai(subclassId: string) {
  const id = normalize(subclassId)
  return id === "samurai" || id === "самурай" || id.endsWith("-samurai")
}

const featureAliases = new Map<string, FeatureCopy>()

function addFeature(level: number, names: string[], copy: FeatureCopy) {
  for (const name of names) featureAliases.set(`${level}:${normalize(name)}`, copy)
}

