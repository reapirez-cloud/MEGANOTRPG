create or replace function private.monk_text_feature(
  p_id text,
  p_source_key text,
  p_label text,
  p_description text,
  p_author_explanation text,
  p_author_comment text default ''
)
returns jsonb
language sql
immutable
set search_path = ''
as $$
  select jsonb_build_object(
    'id', p_id,
    'type', 'grant',
    'target', 'feature',
    'key', p_source_key,
    'sourceKey', p_source_key,
    'payload', jsonb_strip_nulls(jsonb_build_object(
      'label', p_label,
      'description', p_description,
      'authorExplanation', nullif(trim(coalesce(p_author_explanation, '')), ''),
      'authorComment', nullif(trim(coalesce(p_author_comment, '')), '')
    ))
  );
$$;

